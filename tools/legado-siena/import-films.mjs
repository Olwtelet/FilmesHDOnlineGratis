// One-off importer: reads the Webflow "Films" CMS fields that the shared nav renders from
// reference/localized and writes src/data/films.ts (typed FILMS array).
//   - title / category / year / minutes / image  <- home nav, ".menu-coll-w" items (CMS order)
//   - director                                     <- home nav, ".menu-footage-w" items
//   - synopsis                                     <- films_<slug> nav, ".case-menu-tx" (raw text)
// Usage: node tools/import-films.mjs   (re-run only if the reference is re-downloaded)
import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'parse5';

const ROOT = path.resolve(import.meta.dirname, '..');
const read = (page) => parse(fs.readFileSync(path.join(ROOT, 'reference/localized', `${page}.html`), 'utf8'));
const attr = (n, k) => n.attrs?.find((a) => a.name === k)?.value;
const hasClass = (n, c) => (attr(n, 'class') || '').split(/\s+/).includes(c);
function findAll(n, pred, acc = []) {
  if (n.tagName && pred(n)) acc.push(n);
  for (const c of n.childNodes || []) findAll(c, pred, acc);
  return acc;
}
const find = (n, pred) => findAll(n, pred)[0];
const byClass = (n, c) => find(n, (x) => hasClass(x, c));
const text = (n) => (n.childNodes || []).map((c) => (c.nodeName === '#text' ? c.value : text(c))).join('');

const home = read('home');
const nav = byClass(home, 'nav-w');
const rows = byClass(nav, 'menu-coll-w').childNodes.filter((n) => n.tagName);
const footage = byClass(nav, 'menu-footage-w').childNodes.filter((n) => n.tagName);
if (rows.length !== footage.length) throw new Error('nav lists differ in length');

const films = rows.map((row, i) => {
  const slug = attr(row, 'data-id');
  const img = byClass(row, 'menu-main-film-img');
  const info = findAll(row, (n) => hasClass(n, 'info-grid-tx'));
  const minutes = text(byClass(row, 'text-block-6'));
  const foot = footage[i];
  const href = attr(byClass(foot, 'footagemenu-cta-w'), 'href');
  if (href !== `/films/${slug}`) throw new Error(`footage item ${i} links to ${href}, expected /films/${slug}`);
  const footTitles = findAll(foot, (n) => hasClass(n, 'footage-menu-title'));
  const casePage = read(`films_${slug}`);
  const synopsis = text(byClass(byClass(casePage, 'nav-w'), 'case-menu-tx'));
  const image = { src: attr(img, 'src') };
  if (attr(img, 'srcset')) image.srcset = attr(img, 'srcset');
  return {
    slug,
    title: text(byClass(row, 'top-m-film-title')),
    category: text(info[0]),
    year: Number(text(info[1])),
    minutes: Number(minutes),
    director: text(footTitles[1]),
    synopsis,
    image,
  };
});

const out = `// GENERATED by tools/import-films.mjs from reference/localized (Webflow "Films" CMS collection).
// Safe to hand-edit; re-running the importer overwrites this file.
//
// FILMS is in CMS order (the order every collection list on the site uses: nav menus, /work,
// home rolls). Page agents import it read-only and keep page-specific fields in their own data
// modules keyed by slug.

export interface FilmImage {
  /** original asset (largest rendition) */
  src: string;
  /** Webflow responsive renditions; absent when the CMS image has none (then omit sizes too) */
  srcset?: string;
}

export interface Film {
  /** CMS slug: route /films/<slug>, data-id in the nav menu */
  slug: string;
  title: string;
  /** "Documentary" | "Feature Film" | "Short Film" */
  category: string;
  year: number;
  minutes: number;
  director: string;
  /**
   * Synopsis exactly as published (Webflow plain-text field): may contain line breaks and ends
   * with "\\n" for most films; render with {film.synopsis}, do not trim.
   */
  synopsis: string;
  /** main/thumbnail image (nav menus); \`sizes\` depends on the usage (nav: 100vw / 70px) */
  image: FilmImage;
}

export const FILMS: Film[] = ${JSON.stringify(films, null, 2)};

export const filmHref = (slug: string) => \`/films/\${slug}\`;

export function getFilm(slug: string): Film {
  const film = FILMS.find((f) => f.slug === slug);
  if (!film) throw new Error(\`unknown film slug "\${slug}"\`);
  return film;
}
`;
fs.mkdirSync(path.join(ROOT, 'src/data'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/data/films.ts'), out);
console.log(`wrote src/data/films.ts (${films.length} films: ${films.map((f) => f.slug).join(', ')})`);
