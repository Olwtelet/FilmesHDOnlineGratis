// One-off importer: reads the /work-specific fields of the Webflow "Films" CMS collection from
// reference/localized/work.html and writes src/data/work.ts.
//   - location        <- ".work-roll-item" call-outs (2nd ".linecallout-item")
//   - poster          <- ".work-roll-item" img[data-roll=img] (src / srcset; sizes is per usage)
//   - frames          <- ".work-overl-coll" lightbox JSON (script.w-json), same CMS order
// Title / category / year come from src/data/films.ts (FILMS); this script checks that the
// published /work markup agrees with it and that both collection lists follow FILMS order.
// Usage: node tools/import-work.mjs   (re-run only if the reference is re-downloaded)
import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'parse5';
import { FILMS } from '../src/data/films.ts';

const ROOT = path.resolve(import.meta.dirname, '..');
const doc = parse(fs.readFileSync(path.join(ROOT, 'reference/localized/work.html'), 'utf8'));
const attr = (n, k) => n.attrs?.find((a) => a.name === k)?.value;
const hasClass = (n, c) => (attr(n, 'class') || '').split(/\s+/).includes(c);
function findAll(n, pred, acc = []) {
  if (n.tagName && pred(n)) acc.push(n);
  for (const c of n.childNodes || []) findAll(c, pred, acc);
  return acc;
}
const byClass = (n, c) => findAll(n, (x) => hasClass(x, c));
const text = (n) => (n.childNodes || []).map((c) => (c.nodeName === '#text' ? c.value : text(c))).join('');
const fail = (msg) => {
  throw new Error(msg);
};

const POSTER_SIZES = '(max-width: 767px) 75vw, (max-width: 991px) 41vw, 32vw';
const rows = byClass(doc, 'work-roll-item');
const boxes = byClass(byClass(doc, 'work-overl-coll')[0], 'w-dyn-item');
if (rows.length !== FILMS.length || boxes.length !== FILMS.length) fail('collection lengths differ from FILMS');

const work = rows.map((row, i) => {
  const film = FILMS[i];
  const slug = attr(row, 'data-url');
  if (slug !== film.slug) fail(`roll item ${i} is ${slug}, FILMS has ${film.slug}`);
  const callouts = byClass(byClass(row, 'linecallout-list')[0], 'linecallout-item').map((li) =>
    findAll(li, (n) => n.tagName === 'div' && !attr(n, 'class')).map(text),
  );
  const [[, year], [, location], [, category]] = callouts;
  if (text(byClass(row, 'roll-cont-he')[0]) !== film.title) fail(`${slug}: title differs from FILMS`);
  if (category !== film.category || text(byClass(row, 'roll-cont-eyeb')[0]) !== film.category) fail(`${slug}: category differs`);
  if (Number(year) !== film.year) fail(`${slug}: year differs`);

  const img = findAll(row, (n) => n.tagName === 'img')[0];
  const poster = { src: attr(img, 'src') };
  if (attr(img, 'srcset')) {
    poster.srcset = attr(img, 'srcset');
    if (attr(img, 'sizes') !== POSTER_SIZES) fail(`${slug}: unexpected sizes`);
  }

  const script = findAll(boxes[i], (n) => n.tagName === 'script')[0];
  const raw = text(script);
  const json = JSON.parse(raw);
  if (JSON.stringify(json, null, 2) !== raw) fail(`${slug}: lightbox JSON is not 2-space JSON.stringify output`);
  if (json.group !== '' || json.items.some((it) => it.type !== 'image' || Object.keys(it).join() !== 'url,type'))
    fail(`${slug}: unexpected lightbox JSON shape`);
  const frames = json.items.map((it) => it.url);
  if (frames.some((u) => !u.startsWith(`/assets/img/films/${slug}/`))) fail(`${slug}: lightbox frames of another film`);
  return { slug, location, poster, frames };
});

const out = `// GENERATED by tools/import-work.mjs from reference/localized/work.html (Webflow "Films" CMS
// fields used only by /work). Safe to hand-edit; re-running the importer overwrites this file.
// Title, category and year come from FILMS (src/data/films.ts); WORK_FILMS follows FILMS order.

export interface WorkPoster {
  /** original asset (largest rendition) */
  src: string;
  /** Webflow responsive renditions; absent when the CMS image has none (then omit sizes too) */
  srcset?: string;
}

export interface WorkFilm {
  slug: string;
  /** "Location" call-out */
  location: string;
  /** carousel poster (img[data-roll=img]) */
  poster: WorkPoster;
  /** footage stills of the Webflow lightbox (script.w-json); empty when the CMS field is empty */
  frames: string[];
}

/** sizes attribute of the carousel posters (only emitted with a srcset) */
export const WORK_POSTER_SIZES = ${JSON.stringify(POSTER_SIZES)};

export const WORK_FILMS: WorkFilm[] = ${JSON.stringify(work, null, 2)};

export const getWorkFilm = (slug: string): WorkFilm | undefined => WORK_FILMS.find((w) => w.slug === slug);
`;
fs.writeFileSync(path.join(ROOT, 'src/data/work.ts'), out);
console.log(`wrote src/data/work.ts (${work.length} films, ${work.reduce((n, w) => n + w.frames.length, 0)} frames)`);
