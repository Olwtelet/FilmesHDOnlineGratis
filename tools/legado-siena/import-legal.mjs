// One-off importer: reads the three legal pages (/cookies, /terms, /privacy) from
// reference/localized and writes src/data/legal.ts (typed LEGAL_PAGES record).
//   - title / wfPage  <- <title>, <html data-wf-page>
//   - heading         <- the rich text's first <h1>
//   - blocks          <- every following child of .policy-rich-tx (h1 / h3 / p / ul[role=list]),
//                        inline markup (<strong>, <a>, <sub>) kept as an HTML string per block
// Usage: node tools/import-legal.mjs   (re-run only if the reference is re-downloaded)
import fs from 'node:fs';
import path from 'node:path';
import { parse, serialize } from 'parse5';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'src/data/legal.ts');
const SLUGS = ['cookies', 'terms', 'privacy'];

const attr = (n, k) => n.attrs?.find((a) => a.name === k)?.value;
const hasClass = (n, c) => (attr(n, 'class') || '').split(/\s+/).includes(c);
function find(n, pred) {
  if (n.tagName && pred(n)) return n;
  for (const c of n.childNodes || []) {
    const r = find(c, pred);
    if (r) return r;
  }
  return null;
}
const elements = (n) => n.childNodes.filter((c) => c.tagName);
const text = (n) => (n.childNodes || []).map((c) => (c.nodeName === '#text' ? c.value : text(c))).join('');
const fail = (msg) => {
  throw new Error(msg);
};

/** invisible / line-breaking characters, written as escapes in the generated source */
const INVISIBLE = new RegExp(`[${[0x0a, 0xa0, 0x200b, 0x200c, 0x200d, 0x2028, 0x2029].map((c) => String.fromCharCode(c)).join('')}]`, 'g');
const BS = String.fromCharCode(92); // backslash
const escapeChar = (c) => (c.charCodeAt(0) === 0x0a ? `${BS}n` : `${BS}u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);

/** single-quoted JS string literal (invisible characters such as nbsp / zero-width joiner escaped) */
const lit = (s) => "'" + s.split(BS).join(BS + BS).split("'").join(BS + "'").replace(INVISIBLE, escapeChar) + "'";

function importPage(slug) {
  const doc = parse(fs.readFileSync(path.join(ROOT, 'reference/localized', `${slug}.html`), 'utf8'));
  const html = find(doc, (n) => n.tagName === 'html');
  const title = text(find(doc, (n) => n.tagName === 'title'));
  const rich = find(doc, (n) => hasClass(n, 'policy-rich-tx'));
  if (!rich) fail(`${slug}: no .policy-rich-tx`);
  if (rich.childNodes.some((c) => c.nodeName === '#text' && c.value.trim())) fail(`${slug}: loose text in rich text`);
  const [first, ...rest] = elements(rich);
  if (first.tagName !== 'h1' || first.attrs.length || elements(first).length) fail(`${slug}: rich text does not start with a plain <h1>`);
  const blocks = rest.map((n) => {
    if (n.tagName === 'ul') {
      if (n.attrs.length !== 1 || attr(n, 'role') !== 'list') fail(`${slug}: unexpected <ul> attributes`);
      const items = elements(n);
      if (items.some((li) => li.tagName !== 'li' || li.attrs.length)) fail(`${slug}: unexpected list item`);
      return { tag: 'ul', items: items.map((li) => serialize(li)) };
    }
    if (!['h1', 'h3', 'p'].includes(n.tagName) || n.attrs.length) fail(`${slug}: unexpected block <${n.tagName}>`);
    return { tag: n.tagName, html: serialize(n) };
  });
  return { slug, path: `/${slug}`, title, wfPage: attr(html, 'data-wf-page'), heading: text(first), blocks };
}

const block = (b) =>
  b.tag === 'ul'
    ? `      {\n        tag: 'ul',\n        items: [\n${b.items.map((i) => `          ${lit(i)},`).join('\n')}\n        ],\n      },`
    : `      { tag: '${b.tag}', html: ${lit(b.html)} },`;

const pages = SLUGS.map(importPage);
const out = `// GENERATED by tools/import-legal.mjs from reference/localized (the three legal pages).
// Safe to hand-edit; re-running the importer overwrites this file.
//
// Each page is one Webflow Rich Text element (.policy-rich-tx.w-richtext): the leading <h1> is
// \`heading\`, everything after it is \`blocks\`, in order. Block / list-item \`html\` is the inline
// rich-text markup exactly as published (<strong>, <a href>, <sub>; entities as serialized).
// The last two blocks of every page (an <h1> holding only a zero-width joiner and a
// "Subscript" paragraph) are Webflow placeholder leftovers that the live site publishes too.

export type LegalSlug = 'cookies' | 'terms' | 'privacy';

export type LegalBlock =
  | { tag: 'h1' | 'h3' | 'p'; /** inline HTML */ html: string }
  | { tag: 'ul'; /** inline HTML of each <li> (rendered as ul[role=list]) */ items: string[] };

export interface LegalPage {
  /** route, also the "current" link marked in the nav and footer */
  path: string;
  title: string;
  /** Webflow page id: <html data-wf-page> and the footer newsletter form */
  wfPage: string;
  /** first <h1> of the rich text */
  heading: string;
  blocks: LegalBlock[];
}

export const LEGAL_PAGES: Record<LegalSlug, LegalPage> = {
${pages
  .map(
    (p) => `  ${p.slug}: {
    path: ${lit(p.path)},
    title: ${lit(p.title)},
    wfPage: ${lit(p.wfPage)},
    heading: ${lit(p.heading)},
    blocks: [
${p.blocks.map(block).join('\n')}
    ],
  },`
  )
  .join('\n')}
};
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)} (${pages.map((p) => `${p.slug}: ${p.blocks.length} blocks`).join(', ')})`);
